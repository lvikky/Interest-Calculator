    COUNT(*) AS SOURCE_ROWS,
    SUM(CASE WHEN DTSETTLE IS NULL THEN 1 ELSE 0 END) AS ORIGINATION_FALLBACK_ROWS,
    SUM(CASE WHEN DTEND IS NULL THEN 1 ELSE 0 END) AS MATURITY_FALLBACK_ROWS,
    SUM(CASE WHEN DTEND < TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD') THEN 1 ELSE 0 END) AS PAST_MATURITY_ROWS,
    SUM(CASE WHEN DTSETTLE > TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD') THEN 1 ELSE 0 END) AS FUTURE_SETTLEMENT_ROWS,
    SUM(CASE WHEN COALESCE(DTEND, DATEADD(DAY, 1, TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD')))
                      < COALESCE(DTSETTLE, TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD')) THEN 1 ELSE 0 END) AS OUTPUT_DATE_ORDER_ERRORS,
    SUM(CASE WHEN STRANREF IS NULL OR TRIM(STRANREF) = '' THEN 1 ELSE 0 END) AS MISSING_REFERENCE_ROWS,
    SUM(CASE WHEN DLOCALNOTIONAL IS NULL OR DLOCALVALUATIONAMOUNT IS NULL THEN 1 ELSE 0 END) AS NULL_LOCAL_BALANCE_ROWS,
    SUM(CASE WHEN DNOTIONAL IS NULL OR DSPOTVALUATIONAMOUNT IS NULL THEN 1 ELSE 0 END) AS NULL_SPOT_BALANCE_ROWS,
    SUM(CASE WHEN DLOCALVALUATIONAMOUNT = 0 THEN 1 ELSE 0 END) AS ZERO_LOCAL_VALUATION_ROWS,
    SUM(CASE WHEN DSPOTVALUATIONAMOUNT = 0 THEN 1 ELSE 0 END) AS ZERO_SPOT_VALUATION_ROWS,
    SUM(CASE WHEN DLOCALNOTIONAL - DLOCALVALUATIONAMOUNT = 0 THEN 1 ELSE 0 END) AS ZERO_LOCAL_UNUSED_ROWS,
    SUM(CASE WHEN DNOTIONAL - DSPOTVALUATIONAMOUNT = 0 THEN 1 ELSE 0 END) AS ZERO_SPOT_UNUSED_ROWS,
    SUM(CASE WHEN DLOCALNOTIONAL - DLOCALVALUATIONAMOUNT < 0 THEN 1 ELSE 0 END) AS NEGATIVE_LOCAL_UNUSED_ROWS,
    SUM(CASE WHEN DNOTIONAL - DSPOTVALUATIONAMOUNT < 0 THEN 1 ELSE 0 END) AS NEGATIVE_SPOT_UNUSED_ROWS,
    SUM(CASE WHEN DLOCALNOTIONAL < 0 OR DLOCALVALUATIONAMOUNT < 0
               OR DNOTIONAL < 0 OR DSPOTVALUATIONAMOUNT < 0 THEN 1 ELSE 0 END) AS NEGATIVE_INPUT_ROWS
FROM S
GROUP BY ENTITYDIMID, CURRENCYDIMID, VALUATIONTYPEDIMID, SLDATASOURCEDIMID
ORDER BY ENTITYDIMID, CURRENCYDIMID, VALUATIONTYPEDIMID;
