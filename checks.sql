WITH S AS (SELECT GL.*
    FROM TABLE($GlSubLedger) GL
    WHERE GL.VALUATIONDATEDIMID = $P_dtProcessStart
      AND TRIM(GL.SSOURCEACCOUNT) = '0'
      AND EXISTS (
          SELECT 1 FROM TABLE($BankonlyProductType) MAP
          WHERE MAP.PRODUCTTYPEDIMID = GL.PRODUCTTYPEDIMID
            AND TRIM(TO_VARCHAR(MAP.TRN_KIND_ORG_CD)) = '200'
      )),
B AS (SELECT GLSUBLEDGERFACTID, COUNT(*) AS BASE_ROWS FROM S GROUP BY GLSUBLEDGERFACTID),
J AS (
    SELECT GL.GLSUBLEDGERFACTID, COUNT(*) AS JOINED_ROWS,
        SUM(CASE WHEN E.ENTITYDIMID IS NULL OR NULLIF(TRIM(E.SENTITYCODE), '') IS NULL THEN 1 ELSE 0 END) AS BAD_ENTITY_ROWS,
        SUM(CASE WHEN DS.DATASOURCEDIMID IS NULL OR NULLIF(TRIM(DS.SDATASOURCENAME), '') IS NULL THEN 1 ELSE 0 END) AS BAD_SOURCE_ROWS,
        SUM(CASE WHEN AC.ACCOUNTDIMID IS NULL OR NULLIF(TRIM(AC.SACCOUNTNUMBER), '') IS NULL THEN 1 ELSE 0 END) AS BAD_GCIF_ROWS,
        SUM(CASE WHEN PA.PARENTACCOUNTDIMID IS NULL OR NULLIF(TRIM(PA.SPARENTACCOUNTNUMBER), '') IS NULL THEN 1 ELSE 0 END) AS BAD_CCIF_ROWS,
        SUM(CASE WHEN MF.MFGCOMPANYDIMID IS NULL OR NULLIF(TRIM(MF.SMFGCOMPANYCODE), '') IS NULL THEN 1 ELSE 0 END) AS BAD_MFG_ROWS,
        SUM(CASE WHEN CUR.CURRENCYDIMID IS NULL OR NULLIF(TRIM(CUR.SCURRENCYCODEISO), '') IS NULL THEN 1 ELSE 0 END) AS BAD_CURRENCY_ROWS,
        SUM(CASE WHEN PT.PRODUCTTYPEDIMID IS NULL OR NULLIF(TRIM(PT.SPRODUCTTYPE), '') IS NULL THEN 1 ELSE 0 END) AS BAD_PRODUCT_ROWS
    FROM S GL 
LEFT JOIN TABLE($Entity) E
    ON E.ENTITYDIMID = GL.ENTITYDIMID
-- LEFT JOIN keeps missing dimension mappings visible for validation.
LEFT JOIN TABLE($DataSource) DS
    ON DS.DATASOURCEDIMID = GL.SLDATASOURCEDIMID
LEFT JOIN TABLE($Account) AC
    ON AC.ACCOUNTDIMID = GL.CPTYACCOUNTDIMID
LEFT JOIN TABLE($ParentAccount) PA
    ON PA.PARENTACCOUNTDIMID = AC.PARENTACCOUNTDIMID
LEFT JOIN TABLE($MfgCompany) MF
    ON MF.MFGCOMPANYDIMID = AC.MFGCOMPANYDIMID
LEFT JOIN TABLE($Currency) CUR
    ON CUR.CURRENCYDIMID = GL.CURRENCYDIMID
LEFT JOIN TABLE($ProductType) PT
    ON PT.PRODUCTTYPEDIMID = GL.PRODUCTTYPEDIMID
LEFT JOIN (
    SELECT DISTINCT X.THEIR_KEY_C
    FROM TABLE($CounterParty) CP
    INNER JOIN TABLE($CpXref) X
        ON X.CP_ID = CP.CP_ID
    INNER JOIN TABLE($SicCodeRef) SIC
        ON SIC.SIC = CP.SIC_CODE
    WHERE X.SYSTEM = 'G-CIF'
      AND UPPER(SIC.ACD_DESCRIPTION) IN (
          'BANKS && INVESTMENT MANAGEMENT',
          'OTHER FINANCIALS',
          'INSURANCE',
          'REAL ESTATE/REAL ESTATE INVESTMENT TRUSTS'
      )
) FF
    ON FF.THEIR_KEY_C = AC.SACCOUNTNUMBER
    GROUP BY GL.GLSUBLEDGERFACTID
)
SELECT B.GLSUBLEDGERFACTID, B.BASE_ROWS, J.JOINED_ROWS,
    J.BAD_ENTITY_ROWS, J.BAD_SOURCE_ROWS, J.BAD_GCIF_ROWS, J.BAD_CCIF_ROWS,
    J.BAD_MFG_ROWS, J.BAD_CURRENCY_ROWS, J.BAD_PRODUCT_ROWS
FROM B JOIN J ON B.GLSUBLEDGERFACTID = J.GLSUBLEDGERFACTID
    OR (B.GLSUBLEDGERFACTID IS NULL AND J.GLSUBLEDGERFACTID IS NULL)
WHERE J.JOINED_ROWS <> B.BASE_ROWS OR J.BAD_ENTITY_ROWS > 0 OR J.BAD_SOURCE_ROWS > 0
   OR J.BAD_GCIF_ROWS > 0 OR J.BAD_CCIF_ROWS > 0 OR J.BAD_MFG_ROWS > 0
   OR J.BAD_CURRENCY_ROWS > 0 OR J.BAD_PRODUCT_ROWS > 0;
