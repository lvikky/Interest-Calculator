SELECT
    E.SENTITYCODE AS ENTITY,
    DS.SDATASOURCENAME AS SOURCE_SYSTEM,
    'Loans' AS GL_CATEGORY,
    'Uncommitted Lines' AS PRODUCT_DESCRIPTION,
    TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD') AS AS_OF_DATE,
    GL.STRANREF AS DEAL_REFERENCE,
    GL.STRANREF AS LEG_ID,
    CUR.SCURRENCYCODEISO AS CURRENCY,
    COALESCE(
        GL.DTSETTLE,
        TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD')
    ) AS ORIGINATION_DATE,
    COALESCE(
        GL.DTEND,
        DATEADD(DAY, 1, TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD'))
    ) AS MATURITY_DATE,
    'Liability' AS GL_TYPE,

    -- These exact NUMBER columns are confirmed in the new metadata.
    -- Their limit/used meanings and liability sign remain provisional.
    -(GL.DLOCALNOTIONAL - GL.DLOCALVALUATIONAMOUNT) AS ORIGINAL_BALANCE_LCY,
    -(GL.DNOTIONAL - GL.DSPOTVALUATIONAMOUNT) AS PRINCIPAL_OS_LCY,

    NULL AS ACCRUED_INTEREST,
    0 AS EFFECTIVE_INTEREST_RATE,
    'Next' AS BDC,
    'NYB' AS CALENDAR,
    'Bullet' AS PAYMENT_TYPE,
    COALESCE(
        GL.DTSETTLE,
        TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD')
    ) AS PREV_PRIN_PAY_DATE,
    COALESCE(
        GL.DTEND,
        DATEADD(DAY, 1, TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD'))
    ) AS NEXT_PRIN_PAY_DATE,
    'On Maturity' AS FREQUENCY_PRINCIPAL,
    -(GL.DNOTIONAL - GL.DSPOTVALUATIONAMOUNT) AS PRINCIPAL_AMORT_AMOUNT,
    COALESCE(
        GL.DTSETTLE,
        TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD')
    ) AS PREV_INTEREST_PAY_DATE,
    COALESCE(
        GL.DTEND,
        DATEADD(DAY, 1, TRY_TO_DATE(TO_VARCHAR(GL.VALUATIONDATEDIMID), 'YYYYMMDD'))
    ) AS NEXT_INTEREST_PAY_DATE,
    'On Maturity' AS FREQUENCY_INTEREST,
    NULL AS INTEREST_OFFSET_DAYS,
    '30/360' AS ACCRUAL_BASIS,
    NULL AS RATE_SPREAD,
    NULL AS RATE_FLOOR,
    NULL AS NOTIONAL_EXCHANGE,
    (
        SELECT COALESCE(MAX(VERSION_ID), 0) + 1
        FROM TABLE($BANKING_LOANS)
        WHERE AS_OF_DATE BETWEEN
            TRY_TO_DATE($P_dtProcessStart, 'YYYYMMDD')
            AND TRY_TO_DATE($P_dtProcessEnd, 'YYYYMMDD')
    ) AS VERSION_ID,
    NULL AS END_OF_MONTH,
    NULL AS RATE_FLAG,
    NULL AS RATE_CHANGE_FREQUENCY,
    NULL AS RATE_INDEX,
    NULL AS RATE_CEILING,
    NULL AS LAST_RESET_DATE,
    NULL AS NEXT_RESET_DATE,
    NULL AS ENCUMBERANCE,
    NULL AS ENCUMBERANCE_TERM_DATE,
    'Active' AS CREDIT_STATUS,
    NULL AS SECURED_TRANSACTION,
    CASE
        WHEN AC.MFGCOMPANYDIMID <> -1 THEN 'Internal'
        ELSE 'External'
    END AS INTERNAL_FLAG,
    CASE
        WHEN FF.THEIR_KEY_C IS NOT NULL THEN 'Financial'
        ELSE 'Non Financial'
    END AS FINANCIAL_FLAG,
    NULL AS DIVISION,
    AC.SACCOUNTNUMBER AS GCIF,
    PA.SPARENTACCOUNTNUMBER AS CCIF,
    AC.SACCOUNTNAME AS CUST_NAME,
    NULL AS TD_BUYBACK_FLAG,
    NULL AS TD_CONCENTRATION_FLAG_FI_NONFI,
    NULL AS TD_CONCENTRATION_FLAG_NONFI_ONLY,
    CASE
        WHEN MF.SMFGCOMPANYCODE = '400' THEN 'HO'
        WHEN MF.SMFGCOMPANYCODE IN ('667', '661', '662', '726', '684', '655')
            THEN 'INTRA-IHC'
        WHEN MF.SMFGCOMPANYCODE = '500' THEN 'BKNY'
        WHEN MF.SMFGCOMPANYCODE = '646' THEN 'IHC Parent'
        WHEN MF.SMFGCOMPANYCODE = '105' THEN 'IHC CONS'
        WHEN AC.MFGCOMPANYDIMID <> -1
            AND MF.SMFGCOMPANYCODE NOT IN
                ('667', '661', '662', '726', '684', '655', '500', '400', '646', '105')
            THEN 'FG'
        ELSE NULL
    END AS HEAD_OFFICE_FLAG,
    NULL AS SECURITY_HC_LEVEL1,
    NULL AS SECURITY_HC_LEVEL2,
    NULL AS COLLATERAL_TYPE,
    NULL AS CREDIT_RATING,
    '0' AS ACCOUNT_CODE,
    NULL AS CUSIP,
    NULL AS CHAR_CUST_1,
    '200' AS CHAR_CUST_2,
    PT.SPRODUCTTYPE AS CHAR_CUST_3,
    NULL AS NUM_CUST_1,
    NULL AS NUM_CUST_2,
    NULL AS NUM_CUST_3,
    MF.SMFGCOMPANYCODE AS MFG_CODE,
    NULL AS S_EL_GCREATEDEXECUTIONID
FROM TABLE($GlSubLedger) GL
LEFT JOIN TABLE($Entity) E
    ON E.ENTITYDIMID = GL.ENTITYDIMID
-- LEFT JOIN keeps missing dimension mappings visible for validation.
LEFT JOIN TABLE($DataSource) DS
    ON DS.DATASOURCEDIMID = GL.SLDATASOURCEDIMID
LEFT JOIN TABLE($Account) AC
    ON AC.ACCOUNTDIMID = GL.CPTYACCOUNTDIMID
LEFT JOIN TABLE($ParentAccount) PA
    ON PA.PARENTACCOUNTDIMID = AC.PARENTACCOUNTDIMID
LEFT JOIN TABLE($MfgCompany) MF
    ON MF.MFGCOMPANYDIMID = AC.MFGCOMPANYDIMID
LEFT JOIN TABLE($Currency) CUR
    ON CUR.CURRENCYDIMID = GL.CURRENCYDIMID
LEFT JOIN TABLE($ProductType) PT
    ON PT.PRODUCTTYPEDIMID = GL.PRODUCTTYPEDIMID
LEFT JOIN (
    SELECT DISTINCT X.THEIR_KEY_C
    FROM TABLE($CounterParty) CP
    INNER JOIN TABLE($CpXref) X
        ON X.CP_ID = CP.CP_ID
    INNER JOIN TABLE($SicCodeRef) SIC
        ON SIC.SIC = CP.SIC_CODE
    WHERE X.SYSTEM = 'G-CIF'
      AND UPPER(SIC.ACD_DESCRIPTION) IN (
          'BANKS && INVESTMENT MANAGEMENT',
          'OTHER FINANCIALS',
          'INSURANCE',
          'REAL ESTATE/REAL ESTATE INVESTMENT TRUSTS'
      )
) FF
    ON FF.THEIR_KEY_C = AC.SACCOUNTNUMBER
WHERE GL.VALUATIONDATEDIMID = $P_dtProcessStart
  -- NULL/blank account codes are not converted into account code zero.
  AND TRIM(GL.SSOURCEACCOUNT) = '0'
  -- EXISTS prevents repeated rows in the reference map from multiplying balances.
  AND EXISTS (
      SELECT 1
      FROM TABLE($BankonlyProductType) MAP
      WHERE MAP.PRODUCTTYPEDIMID = GL.PRODUCTTYPEDIMID
        AND TRIM(TO_VARCHAR(MAP.TRN_KIND_ORG_CD)) = '200'
  )
